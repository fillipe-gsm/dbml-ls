local support = dofile("spec/support.lua")

describe("hover", function()
  it("describes tables and their columns", function()
    local result = support.hover_at("Table pub|lic.users as U {\n  id integer\n}")
    assert.is_not_nil(result)
    assert.equal("markdown", result.contents.kind)
    assert.matches("%*%*Table%*%* `public.users`", result.contents.value)
    assert.matches("`id`", result.contents.value)
    assert.matches("Alias: `U`", result.contents.value)
  end)

  it("describes columns with type and settings", function()
    local result = support.hover_at("Table users {\n  i|d integer [pk, not null]\n}")
    assert.is_not_nil(result)
    assert.matches("%*%*Column%*%* `users.id`", result.contents.value)
    assert.matches("Type: `integer`", result.contents.value)
    assert.matches("Settings: pk, not null", result.contents.value)
  end)

  it("describes a column's enum type", function()
    local result = support.hover_at("Enum status {\n  active\n}\nTable users {\n  s stat|us\n}")
    assert.is_not_nil(result)
    assert.matches("%*%*Enum%*%* `status`", result.contents.value)
    assert.matches("active", result.contents.value)
  end)

  it("resolves ref endpoints to the referenced column", function()
    local result = support.hover_at("Table users {\n  id integer\n}\nRef: users.i|d < orders.user_id")
    assert.is_not_nil(result)
    assert.matches("%*%*Column%*%* `users.id`", result.contents.value)
  end)

  it("describes the whole ref when hovering the operator", function()
    local result = support.hover_at("Table users {\n  id integer\n}\nRef: users.id <| orders.user_id")
    assert.is_not_nil(result)
    assert.matches("%*%*Ref%*%*", result.contents.value)
    assert.matches("users.id < orders.user_id", result.contents.value)
  end)

  it("returns nothing on whitespace", function()
    assert.is_nil(support.hover_at("Table users {\n  id integer\n}\n  |\n"))
  end)

  it("returns a range covering the hovered token", function()
    local result = support.hover_at("Table us|ers {\n  id integer\n}")
    assert.is_not_nil(result.range)
    assert.is_true(result.range.start.line == 0)
    assert.is_true(result.range["end"].character > result.range.start.character)
  end)
end)
